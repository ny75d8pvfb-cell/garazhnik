_COL = table(["Номинал", "Цвет плоского предохранителя"], [[f'<span class="num">{a} А</span>', f'<span style="display:inline-block;width:14px;height:14px;border-radius:2px;vertical-align:-2px;margin-right:8px;background:{c};border:1px solid rgba(0,0,0,.25)"></span>{E(n)}'] for a, n, c in _fu.COLORS])

def _fuse_article(m):
    cols = m.get("cols")
    head = ["Что не работает"] + (cols if cols else ["Предохранитель"])
    rows = [[f"<b>{E(k)}</b>"] + [f'<span class="num">{E(v)}</span>' for v in ([m["key"][k]] if isinstance(m["key"][k], str) else m["key"][k])] for k in _fu.KEYS if k in m["key"]]
    secs = [("gde", "Где находятся блоки предохранителей", ul([f"<b>{E(t)}.</b> {E(d)}" for t, d in m["where"]]) + tip(E(m["intro"]))),
            ("bystro", "Быстрый поиск: что не работает — какой предохранитель", table(head, rows))]
    for i, (title, brows) in enumerate(m["blocks"]):
        secs.append((f"blok{i+1}", title, table(["№", "Ток, А", "Что защищает"], [[f'<span class="num">{E(n)}</span>', f'<span class="num">{E(a)}</span>', E(c)] for n, a, c in brows])))
    secs.append(("rele", "Реле", table(["Реле", "Где стоит"], [[E(a), E(b)] for a, b in m["relays"]])))
    secs.append(("kak-proverit", "Как проверить и заменить предохранитель", _CHECK))
    secs.append(("cveta", "Цвет предохранителя и ток", _COL + tip("Цвет одинаковый у всех производителей — по нему видно номинал, даже если цифры стёрлись.")))
    secs.append(("sgoraet", "Если предохранитель сгорает снова", _AGAIN))
    others = [s for s in _SLUGS if s != m["slug"]]
    # ближайшие по семейству — первыми
    near = [x["slug"] for x in _fu.M if x["fam"] == m["fam"] and x["slug"] != m["slug"]]
    rel = (near + [s for s in others if s not in near])[:2] + ["lampy-na-paneli"]
    short = m["name"].split(" (")[0]
    add(m["slug"], "Электрика", m["title"],
        f"Где находится блок предохранителей на {short}, за что отвечает каждый предохранитель и реле, номиналы. Какой предохранитель у прикуривателя, печки, бензонасоса, фар. Как проверить и заменить.",
        6, "fuses", "Предохранители в Гаражнике",
        f"Не работает прикуриватель, печка, фара или поворотники? Почти всегда сначала стоит проверить предохранитель. Ниже — где стоят блоки на {short}, быстрая таблица «что не работает — какой предохранитель», полная расшифровка и реле.",
        secs, rel)
    A[-1]["date"] = _D4

for _m in _fu.M:
    _fuse_article(_m)
