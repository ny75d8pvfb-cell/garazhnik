def _reg(k, extra=()):
    rows = []
    for name in ["Масло и масляный фильтр", "Салонный фильтр", "Топливный фильтр", "Антифриз"]:
        w = _sch(k, name)
        if w: rows.append(f"{name} — {w}.")
    grm = _sch(k, "Ремень ГРМ с роликами") or _sch(k, "Ремень ГРМ: осмотр")
    if _sch(k, "Цепь ГРМ: проверка и подтяжка"): rows.append("Цепь ГРМ — проверка и подтяжка " + _sch(k, "Цепь ГРМ: проверка и подтяжка") + ".")
    elif _sch(k, "Ремень ГРМ с роликами"): rows.append("Ремень ГРМ с роликами — " + grm + ".")
    elif grm: rows.append("Ремень ГРМ — осмотр " + grm + ", замена по сервисной книжке и состоянию.")
    return rows + list(extra)

