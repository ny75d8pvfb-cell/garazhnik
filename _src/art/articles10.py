def _v(k, field, i=0):
    return F[k]["engines"][i]["v"][field]

def _sch(k, name):
    for s in D["sched"][k]:
        if s["name"] == name:
            w = []
            if s["km"]: w.append(f'каждые {s["km"]:,} км'.replace(",", " "))
            if s["years"]: w.append("раз в год" if s["years"] == 1 else f'раз в {s["years"]} {"года" if s["years"] < 5 else "лет"}')
            return " или ".join(w)
    return None

