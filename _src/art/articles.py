F = D["fams"]
E = html.escape

def fig(id_, cap=""):
    return f'<figure class="afig">{D["figs"][id_]}{f"<figcaption>{E(cap)}</figcaption>" if cap else ""}</figure>'
def step(id_):
    s = D["steps"][id_]
    return f'<figure class="stepfig">{s["svg"]}<figcaption>{E(s["cap"])}</figcaption></figure>'
def table(head, rows, cls=""):
    th = "".join(f"<th>{E(h)}</th>" for h in head)
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="table {cls}"><table><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>'
def ul(items): return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"
def ol(items): return '<ol class="asteps">' + "".join(f"<li><div>{i}</div></li>" for i in items) + "</ol>"
def warn(t): return f'<div class="warn"><p>{t}</p></div>'
def tip(t): return f'<p class="tip">{t}</p>'
def app(hash_, text): return f'<a class="inlink" href="../#{hash_}">{E(text)}</a>'
def art(slug, text): return f'<a class="inlink" href="{slug}.html">{E(text)}</a>'

def per_engine(field, label_fn=None):
    rows = []
    for k, f in F.items():
        engs = f["engines"]
        vals = [e["v"][field] for e in engs]
        if len(set(vals)) == 1:
            rows.append([f"<b>{E(f['name'])}</b><br><small>{E(f['models'])}</small>", "все моторы", f'<span class="num">{E(vals[0])}</span>'])
        else:
            for i, e in enumerate(engs):
                rows.append([f"<b>{E(f['name'])}</b><br><small>{E(f['models'])}</small>" if i == 0 else "", f"{E(e['name'])}<br><small>{E(e['sub'])}</small>", f'<span class="num">{E(e["v"][field])}</span>'])
    return rows

def sched_rows(k):
    out = []
    for s in D["sched"][k]:
        when = []
        if s["km"]: when.append(f'каждые {s["km"]:,} км'.replace(",", " "))
        if s["years"]: when.append("раз в год" if s["years"] == 1 else f'раз в {s["years"]} {"года" if s["years"] < 5 else "лет"}')
        out.append([E(s["name"]), f'<span class="num">{" или ".join(when)}</span>'])
    return out

def grm_rows():
    rows = []
    for k, f in F.items():
        for i, e in enumerate(f["engines"]):
            rows.append([f"<b>{E(f['name'])}</b>" if i == 0 else "", f"{E(e['name'])}<br><small>{E(e['sub'])}</small>", E(e["v"]["grm"])])
    return rows

def torque_rows():
    rows = []
    for k, f in F.items():
        e0 = f["engines"][0]["v"]
        wheel = f'ключ {E(e0["wheelKey"])} · <span class="num">{E(e0["wheelTorque"])}</span>'
        plugs = sorted({(e["v"]["plugKey"], e["v"]["plugTorque"]) for e in f["engines"]})
        pl = "<br>".join(f'ключ {E(a)} · <span class="num">{E(b)}</span>' for a, b in plugs)
        if k == "vesta":
            wheel = "Веста, Иксрей: ключ 17 · <span class=\"num\">90–120 Н·м</span><br>Ларгус: <span class=\"num\">105 Н·м</span>"
        rows.append([f"<b>{E(f['name'])}</b><br><small>{E(f['models'])}</small>", wheel, pl])
    return rows

